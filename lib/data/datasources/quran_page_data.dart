    if (page <= 20) return 1;
    if (page <= 40) return 2;
    if (page <= 60) return 3;
    if (page <= 80) return 4;
    if (page <= 100) return 5;
    if (page <= 120) return 6;
    if (page <= 140) return 7;
    if (page <= 160) return 8;
    if (page <= 180) return 9;
    if (page <= 200) return 10;
    if (page <= 220) return 11;
    if (page <= 240) return 12;
    if (page <= 260) return 13;
    if (page <= 280) return 14;
    if (page <= 300) return 15;
    if (page <= 320) return 16;
    if (page <= 340) return 17;
    if (page <= 360) return 18;
    if (page <= 380) return 19;
    if (page <= 400) return 20;
    if (page <= 420) return 21;
    if (page <= 440) return 22;
    if (page <= 460) return 23;
    if (page <= 480) return 24;
    if (page <= 500) return 25;
    if (page <= 520) return 26;
    if (page <= 540) return 27;
    if (page <= 560) return 28;
    if (page <= 580) return 29;
    return 30;
  }

  /// Get starting ayah for a page
  static List<int>? getPageStart(int page) {
    return pageStartMapping[page];
  }

  /// Get ending ayah for a page (start of next page - 1)
  static List<int>? getPageEnd(int page) {
    if (page >= totalPages) return [114, 6]; // Last ayah
    return pageStartMapping[page + 1];
  }
